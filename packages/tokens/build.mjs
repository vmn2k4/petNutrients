// Generates the Dart token file from tokens.json. Run: node packages/tokens/build.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));
const out = join(here, '../../apps/mobile/lib/core/theme/tokens.g.dart');

// "#rrggbb" or "#aarrggbb" (alpha first, as Flutter wants it) -> 0xAARRGGBB
const hex = (h) => `Color(0x${(h.length === 7 ? 'ff' + h.slice(1) : h.slice(1)).toUpperCase()})`;
const camel = (k) => k;
const palette = (name, p) => `  static const ${name} = AppPalette(\n${Object.entries(p).map(([k, v]) => `    ${camel(k)}: ${hex(v)},`).join('\n')}\n  );`;
const keys = Object.keys(t.colors.light);

const dart = `// GENERATED by packages/tokens/build.mjs from packages/tokens/tokens.json. Do not edit by hand.
import 'dart:ui' show Color;

/// One full set of semantic colours (light or dark).
class AppPalette {
  const AppPalette({
${keys.map((k) => `    required this.${k},`).join('\n')}
  });
${keys.map((k) => `  final Color ${k};`).join('\n')}
}

class AppColors {
  AppColors._();
${palette('light', t.colors.light)}
${palette('dark', t.colors.dark)}
${Object.entries(t.colors.brand).map(([k, v]) => `  static const brand${k[0].toUpperCase() + k.slice(1)} = ${hex(v)};`).join('\n')}
}

class AppFonts {
  AppFonts._();
${Object.entries(t.fonts).map(([k, v]) => `  static const ${k} = '${v}';`).join('\n')}
}

class AppText {
  AppText._();
${Object.entries(t.textSizes).map(([k, v]) => `  static const double ${k} = ${v}.0;`).join('\n')}
}

class AppSpace {
  AppSpace._();
${Object.entries(t.spacing).map(([k, v]) => `  static const double ${k} = ${v}.0;`).join('\n')}
}

class AppRadius {
  AppRadius._();
${Object.entries(t.radii).map(([k, v]) => `  static const double ${k} = ${v}.0;`).join('\n')}
}

class AppSize {
  AppSize._();
${Object.entries(t.sizes).map(([k, v]) => `  static const double ${k} = ${v}.0;`).join('\n')}
}

class AppMotion {
  AppMotion._();
${Object.entries(t.motionMs).map(([k, v]) => `  static const ${k} = Duration(milliseconds: ${v});`).join('\n')}
}
`;
writeFileSync(out, dart);
console.log('wrote', out);
