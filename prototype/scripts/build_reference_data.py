"""Builds js/reference-data.js from the real datasets in ../../data (growth, breeds, AAFCO)."""
import csv, json, statistics, collections, pathlib
D = pathlib.Path(__file__).resolve().parents[2] / "data"
OUT = pathlib.Path(__file__).resolve().parents[1] / "js" / "reference-data.js"

dog_growth = collections.defaultdict(list)
for r in csv.DictReader(open(D/"growth/salt2017_empirical_weight_by_sizecat_month.csv")):
    dog_growth[r["size_cat"]].append({"m": int(r["age_month"]), **{k: float(r[k]) for k in ("p02","p25","p50","p75","p98")}})

by_month = collections.defaultdict(list)
for r in csv.DictReader(open(D/"growth/extra/salt_kitten_datacat1456/KGC1_dataset.csv")):
    try: by_month[round(float(r["Visit_Age_Yrs"])*12)].append(float(r["Weight_kg"]))
    except ValueError: pass
def pct(v, p):
    v = sorted(v); i = (len(v)-1)*p; lo = int(i); hi = min(lo+1, len(v)-1)
    return v[lo] + (v[hi]-v[lo])*(i-lo)
cat_growth = []
for m in sorted(by_month):
    v = by_month[m]
    if len(v) >= 25 and m <= 36:
        cat_growth.append({"m": m, "n": len(v), **{f"p{int(p*100):02d}": round(pct(v, p), 2) for p in (0.02,0.25,0.5,0.75,0.98)}})

breeds = [{"name": r["breed"], "size": r["size_category"], "min": float(r["adult_weight_min_kg"]), "max": float(r["adult_weight_max_kg"])}
          for r in csv.DictReader(open(D/"growth/breed_growth_index.csv")) if r["adult_weight_min_kg"]]

aafco = collections.defaultdict(dict)
want = {"Crude Protein","Crude Fat","Calcium","Phosphorus","Taurine","Sodium","Zinc","Vitamin D","Vitamin A","Iron"}
for r in csv.DictReader(open(D/"nutrient_profiles/aafco_nutrient_profiles_per1000kcal.csv")):
    if r["nutrient"] in want:
        aafco[r["species"]][r["nutrient"]] = {"unit": r["unit_per_1000kcal_ME"], "growth": r["growth_reproduction_min"], "adult": r["adult_maintenance_min"], "max": r["maximum"]}

# breed facts: typical exercise (Kaggle, CC0, unverified) and conditions with an increased incidence (figshare canine diet datasets, CC BY 4.0)
ex = {r["Name"].lower(): r for r in csv.DictReader(open(D/"breeds/top-dog-breeds-around-the-world/Dog Breads Around The World.csv", encoding="utf-8-sig"))}
dis = collections.defaultdict(set)
for r in csv.DictReader(open(D/"figshare_canine/dog_breed_diseases.csv", encoding="utf-8-sig")):
    if "increased incidence" not in (r["Predisposition_to_disease"] or ""): continue
    names = {r["Breed"].lower()} | {x.strip().lower() for x in (r["Alternative_breed_names"] or "").replace(";", ",").split(",") if x.strip()}
    for n in names: dis[n].add(r["Disease"].strip().lower())
# only conditions where food, weight or feeding can matter (the full list includes many rare genetic conditions)
RELEVANT = ["diabetes", "pancreatitis", "obes", "urolith", "stone", "hip dysplasia", "elbow dysplasia", "osteoarthritis", "cruciate", "gastric dilatation", "bloat", "food allergy", "atopy", "hypothyroid", "cystinuria", "copper", "inflammatory bowel", "protein-losing", "hyperlipid", "kidney", "renal", "periodontal"]
breed_info = {}
for b in breeds:
    k = b["name"].lower(); e = ex.get(k); d = sorted(x for x in dis.get(k, []) if any(w in x for w in RELEVANT))
    hrs = None
    if e:
        try: hrs = float(e["Exercise Requirements (hrs/day)"])
        except (ValueError, KeyError): pass
    if hrs is not None or d: breed_info[b["name"]] = {"ex": hrs, "dis": d[:6]}

OUT.write_text("// GENERATED by scripts/build_reference_data.py from /data. Do not edit by hand.\n"
  "export const DOG_GROWTH = " + json.dumps(dog_growth) + ";\n"
  "export const CAT_GROWTH = " + json.dumps(cat_growth) + ";\n"
  "export const DOG_BREEDS = " + json.dumps(breeds) + ";\n"
  "export const AAFCO = " + json.dumps(aafco) + ";\n"
  "export const BREED_INFO = " + json.dumps(breed_info) + ";\n")
print(len(breed_info), "breeds with extra info;", len(cat_growth), "kitten months;", len(breeds), "breeds;", {k: len(v) for k, v in aafco.items()})
print(cat_growth[:3], cat_growth[-1])
